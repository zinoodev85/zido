#!/usr/bin/env python3
"""Regenerate TODO.md from todos/{open,done}/*/todo.md.

Usage: index.py [--today]
  --today  print a compact "due + high priority" overview to stdout instead.

Env: TODO_HOME (default ~/todos), TODO_LANG (en | de, default en).
"""
import datetime as dt, os, pathlib, re, sys

ROOT = pathlib.Path(os.environ.get("TODO_HOME", pathlib.Path.home() / "todos")).expanduser()
TODAY = dt.date.today()
SOON = TODAY + dt.timedelta(days=7)
PRIO = {"high": 0, "normal": 1, "low": 2}
PRIO_MARK = {"high": "🔴 ", "normal": "", "low": "⚪ "}
LABELS = {
    "en": {"title": "TODOs", "note": "_Generated by `/todo` — do not edit by hand. 🔴 high · ⚪ low_",
           "working": "▶ in progress", "overdue": "⚠️ overdue ", "due": "due ", "soon": "⏰ Due (≤ 7 days)",
           "done": "✅ Done (last 20)", "open": "Open", "due_short": "Due", "high": "High priority",
           "summary": "Open: {} · due ≤ 7 days: {} · high: {}"},
    "de": {"title": "TODOs", "note": "_Generiert von `/todo` — nicht von Hand bearbeiten. 🔴 hoch · ⚪ niedrig_",
           "working": "▶ in Arbeit", "overdue": "⚠️ überfällig ", "due": "fällig ", "soon": "⏰ Fällig (≤ 7 Tage)",
           "done": "✅ Erledigt (letzte 20)", "open": "Offen", "due_short": "Fällig", "high": "Hohe Priorität",
           "summary": "Offen: {} · fällig ≤ 7 Tage: {} · hoch: {}"},
}
L = LABELS.get(os.environ.get("TODO_LANG", "en"), LABELS["en"])


def load(state):
    items = []
    for f in sorted((ROOT / "todos" / state).glob("*/todo.md")):
        text = f.read_text()
        fm = re.match(r"---\n(.*?)\n---", text, re.S)
        meta = dict(re.findall(r"^(\w+):[ \t]*(.*?)(?:[ \t]+#.*)?$", fm.group(1), re.M)) if fm else {}
        links = re.search(r"^## Links\n(.*?)(?=^## |\Z)", text, re.S | re.M)
        names = [p.name for p in f.parent.iterdir()]
        items.append({
            **meta,
            "path": f.relative_to(ROOT).as_posix(),
            "imgs": sum(bool(re.match(r"img\d+\.\w+$", n)) for n in names),
            "atts": sum(bool(re.match(r"(email|text)\d+\.md$", n)) for n in names),
            "links": len(re.findall(r"^- \[", links.group(1), re.M)) if links else 0,
        })
    return items


def due_of(t):
    try:
        return dt.date.fromisoformat(t.get("due", ""))
    except ValueError:
        return None


def row(t, show_project=False):
    parts = [f"- [ ] {PRIO_MARK.get(t.get('priority'), '')}[{t.get('title', '?')}]({t['path']})"]
    if show_project:
        parts.append(f"`{t.get('project', '-')}`")
    if t.get("zidev"):
        parts.append(L["working"])
    due = due_of(t)
    if due:
        parts.append((L["overdue"] if due < TODAY else L["due"]) + due.isoformat())
    extra = " ".join(f"{icon} {n}" for icon, n in (("🖼", t["imgs"]), ("🔗", t["links"]), ("📎", t["atts"])) if n)
    if extra:
        parts.append(extra)
    return " · ".join(parts)


def sort_key(t):
    return (PRIO.get(t.get("priority"), 1), due_of(t) or dt.date.max, t.get("created", ""))


open_items, done_items = load("open"), load("done")
urgent = sorted((t for t in open_items if (due_of(t) and due_of(t) <= SOON)), key=lambda t: due_of(t))

if "--today" in sys.argv:
    high = [t for t in open_items if t.get("priority") == "high" and t not in urgent]
    print(L["summary"].format(len(open_items), len(urgent), len(high) + sum(t.get("priority") == "high" for t in urgent)))
    for title, group in ((L["due_short"], urgent), (L["high"], sorted(high, key=sort_key))):
        if group:
            print(f"\n{title}:")
            print("\n".join(row(t, True) for t in group))
    sys.exit(0)

out = [f"# {os.environ.get('TODO_TITLE', L['title'])}", "", L["note"], ""]
if urgent:
    out += [f"## {L['soon']}", "", *(row(t, True) for t in urgent), ""]
projects = sorted({t.get("project", "-") for t in open_items})
for p in projects:
    out += [f"## {p}", "", *(row(t) for t in sorted((t for t in open_items if t.get("project", "-") == p), key=sort_key)), ""]
recent = sorted(done_items, key=lambda t: t.get("done", ""), reverse=True)[:20]
if recent:
    out += [f"## {L['done']}", ""]
    out += [f"- [x] [{t.get('title', '?')}]({t['path']}) · `{t.get('project', '-')}` · {t.get('done', '')}" for t in recent]
    out.append("")
(ROOT / "TODO.md").write_text("\n".join(out))
